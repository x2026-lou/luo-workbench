  function inferGenre(g, book) {
    if (C[g]) return g;
    const tags = (book.tags || []).join('');
    if (tags.indexOf('校园') >= 0) return '校园';
    if (tags.indexOf('暗恋') >= 0) return '暗恋';
    if (tags.indexOf('百合') >= 0) return '百合';
    return '言情';
  }

